import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";
import { projects } from "../src/lib/content";

// Curated entries from each preview's 16-color quantization. If a preview
// changes, review these samples again rather than silently substituting colors.
const selections: Record<string, readonly string[]> = {
  aetherica: ["#070706", "#342c21", "#b29054", "#e3dabc"],
  "hidden-forces": ["#171410", "#3a2a17", "#696764", "#b0afad"],
  astera: ["#161819", "#222c35", "#7d7d7d", "#f1f2f3"],
  "sky-mathis": ["#050504", "#3a3327", "#95938f", "#e7e4df"],
  "3-magi": ["#000100", "#2a2b2c", "#898781", "#e9e5d9"],
  pigeonshield: ["#172838", "#5780af", "#f1c544", "#fcfdfd"],
  "ocean-ember": ["#faf7f0", "#2d392b", "#cc7822", "#c6c2b7"],
  "7-seas-trading": ["#faf9f2", "#344838", "#809ca0", "#ca805c"],
};

const palettes: Record<
  string,
  { source: string; sha256: string; colors: readonly string[] }
> = {};

for (const project of projects) {
  const source = `public/assets/projects/${project.image}-1200.webp`;
  const input = await readFile(source);
  const quantized = await sharp(input)
    .resize(240)
    .png({ palette: true, colours: 16, dither: 0 })
    .toBuffer();
  const { data } = await sharp(quantized)
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const available = new Set<string>();
  for (let index = 0; index < data.length; index += 3) {
    available.add(`#${data.subarray(index, index + 3).toString("hex")}`);
  }
  const colors = selections[project.id];
  if (
    !colors ||
    colors.length !== 4 ||
    new Set(colors).size !== 4 ||
    colors.some((color) => !available.has(color))
  ) {
    throw new Error(`Review the four preview color samples for ${project.id}.`);
  }
  palettes[project.id] = {
    source,
    sha256: createHash("sha256").update(input).digest("hex"),
    colors,
  };
}

await writeFile(
  "src/lib/project-palettes.ts",
  `// Generated by scripts/project-palettes.ts. See docs/palette-sources.md.
export interface ProjectPalette {
  source: string;
  sha256: string;
  colors: readonly [string, string, string, string];
}

export const projectPalettes: Readonly<Record<string, ProjectPalette>> = ${JSON.stringify(palettes, null, 2)};
`,
);
